def make_glyph(rows, columns, pixel_width, padding, center_stem=False):
    pen = TTGlyphPen(None)
    for row_index, row in enumerate(rows):
        mask = int(row, 16)
        bottom = (len(rows) - 1 - row_index) * 100
        # An even-width cell needs a half-brick offset for a centered single brick.
        offset = pixel_width // 2 if center_stem and mask == 4 else 0
        first_bit = 1 << (columns - 1)
        column = 0
        while column < columns:
            if not mask & (first_bit >> column):
                column += 1
                continue
            start = column
            while column < columns and mask & (first_bit >> column):
                column += 1
            left = start * pixel_width + padding + offset
            right = column * pixel_width + padding + offset
            pen.moveTo((left, bottom))
            pen.lineTo((left, bottom + 100))
            pen.lineTo((right, bottom + 100))
            pen.lineTo((right, bottom))
            pen.closePath()
    return pen.glyph()


def build(rows, family, filename, *, square=False, uppercase=False, attribution=None):
    names = {char: f"uni{ord(char):04X}" for char in rows}
    cmap = {ord(char): name for char, name in names.items()}
    if uppercase:
        cmap.update({ord(char.lower()): names[char] for char in "ABCDEFGHIJKLMNOPQRSTUVWXYZ"})
    grid = (8, 100, 0) if square else (4, 200, 100)
    glyphs = {".notdef": make_glyph(rows["?"], *grid)}
    glyphs.update({
        name: make_glyph(rows[char], *grid, center_stem=not square and char in "IT")
        for char, name in names.items()
    })
    em, advance, ascent, descent, cap_height = (
        (800, 800, 800, 0, 700) if square else (1200, 1000, 1100, 100, 1000)
    )
    metrics = {
        name: (advance, min((x for x, _ in glyph.coordinates), default=0))
        for name, glyph in glyphs.items()
    }
    font = FontBuilder(em, isTTF=True)
    font.setupGlyphOrder(list(glyphs))
    font.setupCharacterMap(cmap)
    font.setupGlyf(glyphs)
    font.setupHorizontalMetrics(metrics)
    font.setupHorizontalHeader(ascent=ascent, descent=-descent)
    version = "1.0" if square else "1.1"
    font.setupNameTable({
        "familyName": family, "styleName": "Regular",
        "uniqueFontIdentifier": f"{family} {version}", "fullName": family,
        "psName": family.replace(" ", ""), "version": f"Version {version}",
        **(attribution or {}),
    })
    font.setupOS2(sTypoAscender=ascent, sTypoDescender=-descent,
                  usWinAscent=ascent, usWinDescent=descent, sCapHeight=cap_height)
    font.setupPost(isFixedPitch=1)
    font.font.recalcTimestamp = False
    font.font.flavor = "woff"
    buffer = BytesIO()
    font.save(buffer)
    encoded = b64encode(buffer.getvalue()).decode("ascii")
    css = (
        "/* Generated by tools/build_font.py. */\n"
        "@font-face {\n"
        f'  font-family: "{family}";\n'
        f'  src: url("data:font/woff;base64,{encoded}") format("woff");\n'
        "  font-display: swap;\n"
        "}\n"
    )
    output = Path(__file__).resolve().parents[1] / "dist" / filename
    output.write_text(css, encoding="utf-8", newline="\n")


def read_bitmap(filename):
    rows = {}
    for line in Path(__file__).with_name(filename).read_text().splitlines():
        code, bitmap = line.split()
        rows[chr(int(code, 16))] = [bitmap[i:i + 2] for i in range(0, len(bitmap), 2)]
    return rows


